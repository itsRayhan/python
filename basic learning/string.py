#Python - Slicing Strings
name ='rayhan'
print(name[:6])
print(name[0:-5])
print(name[3:5])
print(name[0:0])
print(name[:-5])
print(name[::5])
print(name[::-3])
print(name[::-1])



#Python - Modify Strings
xyz='rayhan hossen'
print(xyz.upper())
print(xyz.lower())
print(xyz.strip())
print(xyz.replace("hossen", "khan"))
print(xyz.split())
print(xyz.capitalize())
print(xyz.title())


